namespace Atlas.Core.Layout;

/// <summary>
///     Which child owns the fixed size in a FixedPixels basis.
/// </summary>
public enum SplitAnchor
{
    /// <summary>
    ///     The first child holds the fixed size.
    /// </summary>
    First = 0,

    /// <summary>
    ///     The second child holds the fixed size.
    /// </summary>
    Second = 1,
}
