namespace Atlas.Core.Placement;

/// <summary>
/// Identifies a logical inline side independently of text direction.
/// </summary>
public enum LogicalSide
{
    /// <summary>
    /// The inline-start side.
    /// </summary>
    InlineStart = 0,

    /// <summary>
    /// The inline-end side.
    /// </summary>
    InlineEnd = 1,
}
