namespace Atlas.Core.Placement;

/// <summary>
/// Identifies an edge that can host auto-hidden tool items.
/// </summary>
public enum WorkspaceEdge
{
    /// <summary>
    /// The inline-start edge.
    /// </summary>
    InlineStart = 0,

    /// <summary>
    /// The inline-end edge.
    /// </summary>
    InlineEnd = 1,

    /// <summary>
    /// The block-end edge.
    /// </summary>
    BlockEnd = 2,
}
